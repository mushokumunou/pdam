#!/usr/bin/env python3
"""Generate schema/asset_index.sql from templates/*.json index mappings.

The projection `asset_index` is derived data only: triggers on each typed table
(and on its tags junction) recompute one row. Never write to it by hand.
"""
from __future__ import annotations

import glob
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "schema", "asset_index.sql")

HEADER = """-- GENERATED by scripts/build_index_sql.py — edit templates/*.json instead.
-- pdam.asset_index: read model for All-assets list, cross-type search and dashboard.
-- It is a projection: the typed collections remain the only source of truth.

CREATE TABLE IF NOT EXISTS asset_index (
  asset_id     uuid PRIMARY KEY,
  template     varchar(60) NOT NULL,
  name         text,
  status       varchar(32),
  provider_name text,
  account_name  text,
  expires_on   date,
  renewal_on   date,
  tags         text,
  search_text  text,
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS asset_index_template_idx ON asset_index (template);
CREATE INDEX IF NOT EXISTS asset_index_status_idx   ON asset_index (status);
CREATE INDEX IF NOT EXISTS asset_index_expires_idx  ON asset_index (expires_on);
CREATE INDEX IF NOT EXISTS asset_index_renewal_idx  ON asset_index (renewal_on);

"""


def fk_col(path: str | None) -> str | None:
    return path.split(".")[0] if path else None


def build(spec: dict) -> str:
    t = spec["slug"]
    idx = spec.get("index") or {}
    name_col = idx.get("name") or "name"
    prov = fk_col(idx.get("provider"))
    acct = fk_col(idx.get("account"))
    expires = idx.get("expires")
    renewal = idx.get("renewal")
    extras = idx.get("extra") or []

    def exp(col: str | None) -> str:
        return f"r.{col}" if col else "NULL::date"

    search_bits = [f"r.{name_col}", "v_provider", "v_account", "v_tags"]
    search_bits += [f"r.{e}" for e in extras]

    s = []
    s.append(f"-- {t}")
    s.append(f"CREATE OR REPLACE FUNCTION pdam_idx_{t}(p_id uuid) RETURNS void "
             f"LANGUAGE plpgsql AS $fn$\nDECLARE\n"
             f"  r {t}%ROWTYPE;\n  v_tags text;\n  v_provider text;\n  v_account text;\n"
             f"  v_search text;\nBEGIN\n"
             f"  SELECT * INTO r FROM {t} WHERE id = p_id;\n"
             f"  IF NOT FOUND THEN\n"
             f"    DELETE FROM asset_index WHERE asset_id = p_id;\n    RETURN;\n  END IF;\n")
    s.append(f"  SELECT string_agg(g.name, ', ' ORDER BY g.name) INTO v_tags\n"
             f"    FROM {t}_tags j JOIN tags g ON g.id = j.tags_id WHERE j.{t}_id = p_id;\n")
    if prov:
        s.append(f"  SELECT p.name INTO v_provider FROM providers p WHERE p.id = r.{prov};\n")
    else:
        s.append("  v_provider := NULL;\n")
    if acct:
        s.append(f"  SELECT a.name INTO v_account FROM accounts a WHERE a.id = r.{acct};\n")
    else:
        s.append("  v_account := NULL;\n")
    s.append(f"  v_search := lower(concat_ws(' ', {', '.join(search_bits)}));\n")
    s.append(
        "  INSERT INTO asset_index\n"
        "    (asset_id, template, name, status, provider_name, account_name,\n"
        "     expires_on, renewal_on, tags, search_text, updated_at)\n"
        f"  VALUES (r.id, '{t}', r.{name_col}, r.status, v_provider, v_account,\n"
        f"          {exp(expires)}, {exp(renewal)}, v_tags, v_search, now())\n"
        "  ON CONFLICT (asset_id) DO UPDATE SET\n"
        "    template = EXCLUDED.template, name = EXCLUDED.name, status = EXCLUDED.status,\n"
        "    provider_name = EXCLUDED.provider_name, account_name = EXCLUDED.account_name,\n"
        "    expires_on = EXCLUDED.expires_on, renewal_on = EXCLUDED.renewal_on,\n"
        "    tags = EXCLUDED.tags, search_text = EXCLUDED.search_text, updated_at = now();\n"
        "END $fn$;\n")

    s.append(
        f"CREATE OR REPLACE FUNCTION pdam_idx_trg_{t}() RETURNS trigger LANGUAGE plpgsql AS $t$\n"
        f"BEGIN\n"
        f"  IF TG_OP = 'DELETE' THEN\n"
        f"    DELETE FROM asset_index WHERE asset_id = OLD.id;\n    RETURN OLD;\n  END IF;\n"
        f"  PERFORM pdam_idx_{t}(NEW.id);\n  RETURN NEW;\nEND $t$;\n"
        f"DROP TRIGGER IF EXISTS trg_idx_{t} ON {t};\n"
        f"CREATE TRIGGER trg_idx_{t} AFTER INSERT OR UPDATE OR DELETE ON {t}\n"
        f"  FOR EACH ROW EXECUTE FUNCTION pdam_idx_trg_{t}();\n")

    s.append(
        f"CREATE OR REPLACE FUNCTION pdam_idx_jtrg_{t}() RETURNS trigger LANGUAGE plpgsql AS $j$\n"
        f"BEGIN\n  PERFORM pdam_idx_{t}(COALESCE(NEW.{t}_id, OLD.{t}_id));\n  RETURN NULL;\nEND $j$;\n"
        f"DROP TRIGGER IF EXISTS trg_idx_{t}_tags ON {t}_tags;\n"
        f"CREATE TRIGGER trg_idx_{t}_tags AFTER INSERT OR DELETE OR UPDATE ON {t}_tags\n"
        f"  FOR EACH ROW EXECUTE FUNCTION pdam_idx_jtrg_{t}();\n")
    return "\n".join(s)


def main():
    specs = []
    for p in glob.glob(os.path.join(ROOT, "templates", "*.json")):
        spec = json.load(open(p))
        if spec.get("index"):
            specs.append(spec)
    specs.sort(key=lambda s: s.get("sort", 99))

    parts = [HEADER]
    parts += [build(s) for s in specs]

    rebuild = ["CREATE OR REPLACE FUNCTION pdam_index_rebuild() RETURNS void "
               "LANGUAGE plpgsql AS $rb$\nDECLARE r record;\nBEGIN\n  DELETE FROM asset_index;\n"]
    for s in specs:
        rebuild.append(f"  FOR r IN SELECT id FROM {s['slug']} LOOP PERFORM pdam_idx_{s['slug']}(r.id); END LOOP;\n")
    rebuild.append("END $rb$;\n")
    parts.append("".join(rebuild))

    with open(OUT, "w") as fh:
        fh.write("\n".join(parts) + "\n")
    print(f"wrote {OUT} ({len(specs)} templates: {', '.join(s['slug'] for s in specs)})")


if __name__ == "__main__":
    main()
